/* global process */

// Regenerates src/infrastructure/persistence/postgres/migration-manifest.ts
// from the migration files. Run after adding a migration: `npm run db:manifest`.
// Checksum = SHA-256 of the file with CRLF normalized to LF, so Windows
// (autocrlf) and Linux checkouts produce the same value.

const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");

const repositoryRoot = path.resolve(path.dirname(process.argv[1]), "..");
const migrationsDirectory = path.resolve(
  repositoryRoot,
  "src/infrastructure/persistence/postgres/migrations"
);
const manifestPath = path.resolve(
  repositoryRoot,
  "src/infrastructure/persistence/postgres/migration-manifest.ts"
);

const entries = fs
  .readdirSync(migrationsDirectory)
  .filter((file) => file.endsWith(".cjs"))
  .sort()
  .map((file) => {
    const content = fs.readFileSync(path.join(migrationsDirectory, file), "utf8").replace(/\r\n/g, "\n");

    return {
      name: file.slice(0, -".cjs".length),
      sha256: crypto.createHash("sha256").update(content, "utf8").digest("hex")
    };
  });

const body = entries
  .map((entry) => `  { name: "${entry.name}", sha256: "${entry.sha256}" }`)
  .join(",\n");

fs.writeFileSync(
  manifestPath,
  `// GENERATED by scripts/generate-migration-manifest.cjs (npm run db:manifest). Do not edit.
// The last entry is the expected schema head. Changing a migration file
// changes its checksum: historical migrations must never be edited.

export interface MigrationManifestEntry {
  readonly name: string;
  readonly sha256: string;
}

export const MIGRATION_MANIFEST: readonly MigrationManifestEntry[] = [
${body}
];
`
);

process.stdout.write(`Wrote ${entries.length} migration(s); head ${entries[entries.length - 1].name}.\n`);
